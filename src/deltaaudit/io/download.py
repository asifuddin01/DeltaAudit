"""Streamed downloads into fresh empty dirs under data/raw, with pinning (CLAUDE.md rules 7-8)."""

import hashlib
import json
from datetime import UTC, datetime
from pathlib import Path
from urllib.request import Request, urlopen

from tqdm import tqdm

from deltaaudit import __version__
from deltaaudit.io.checksums import RAW_DIR, pin, read_pins, sha256_file
from deltaaudit.io.safe_extract import safe_extract

USER_AGENT = f"deltaaudit/{__version__}"
CHUNK_BYTES = 1 << 20
TIMEOUT_S = 60
DOWNLOADS_FILE = Path("data/downloads.json")
SOURCES_FILE = Path("data/SOURCES.md")


class DownloadError(Exception):
    pass


def stream_download(url: str, dest: Path, expected_md5: str | None = None) -> dict:
    """Stream `url` to `dest`, hashing on the fly. Leaves nothing behind on failure."""
    part = dest.with_name(dest.name + ".part")
    sha, md5 = hashlib.sha256(), hashlib.md5(usedforsecurity=False)
    n = 0
    try:
        req = Request(url, headers={"User-Agent": USER_AGENT})
        with urlopen(req, timeout=TIMEOUT_S) as resp, open(part, "xb") as out:
            if "text/html" in resp.headers.get("Content-Type", ""):
                raise DownloadError(
                    f"{url} returned HTML, not data. The file may have moved; "
                    "check the current GEARS pertdata.py (BUILD_GUIDE Part K)."
                )
            total = int(resp.headers.get("Content-Length") or 0)
            with tqdm(
                total=total or None, unit="B", unit_scale=True, desc=dest.name
            ) as bar:
                while block := resp.read(CHUNK_BYTES):
                    out.write(block)
                    sha.update(block)
                    md5.update(block)
                    n += len(block)
                    bar.update(len(block))
        if total and n != total:
            raise DownloadError(f"truncated download: {n} of {total} bytes")
        if expected_md5 and md5.hexdigest() != expected_md5:
            raise DownloadError(f"md5 {md5.hexdigest()} != expected {expected_md5}")
    except BaseException:
        part.unlink(missing_ok=True)
        raise
    part.rename(dest)
    return {
        "url": url,
        "bytes": n,
        "sha256": sha.hexdigest(),
        "md5": md5.hexdigest(),
        "downloaded_utc": datetime.now(UTC).isoformat(timespec="seconds"),
    }


def _visible_files(d: Path) -> list[Path]:
    return [
        p
        for p in d.rglob("*")
        if p.is_file() and not any(s.startswith(".") for s in p.relative_to(d).parts)
    ]


def fetch_asset(root: Path, dataset: str, asset: dict) -> dict:
    """Download (and extract) one asset into data/raw/<dataset>/<asset id>/ and pin every file.

    An existing non-empty directory is accepted only if it is a complete, verified download;
    anything else is reported, never cleaned up automatically.
    """
    asset_dir = root / RAW_DIR / dataset / asset["id"]
    archive = asset_dir / asset["filename"]
    if asset_dir.exists() and any(asset_dir.iterdir()):
        pins = read_pins(root)
        files = _visible_files(asset_dir)
        ok = archive.exists() and all(
            pins.get(p.relative_to(root).as_posix()) == sha256_file(p) for p in files
        )
        if ok:
            return {"status": "present (verified)"}
        raise DownloadError(
            f"{asset_dir} is not empty and is not a verified download. Inspect it by hand; "
            "data/raw is never modified automatically."
        )

    asset_dir.mkdir(parents=True, exist_ok=True)
    rec = stream_download(asset["url"], archive, asset.get("md5"))
    pin(root, archive, rec["sha256"])
    if asset.get("archive"):
        extracted = safe_extract(archive, asset_dir / "extracted")
        for f in extracted:
            pin(root, f, sha256_file(f))
        rec["extracted"] = [f.relative_to(root).as_posix() for f in extracted]
    _record(root, dataset, asset["id"], rec)
    return {"status": "downloaded", **rec}


def _record(root: Path, dataset: str, asset_id: str, rec: dict) -> None:
    """Keep the first download record per asset (committed; feeds SOURCES.md)."""
    path = root / DOWNLOADS_FILE
    data = json.loads(path.read_text()) if path.exists() else {}
    data.setdefault(dataset, {}).setdefault(asset_id, rec)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n")


def render_sources(root: Path, configs: list[dict]) -> Path:
    """Write data/SOURCES.md from the dataset configs and the download records."""
    records = (
        json.loads((root / DOWNLOADS_FILE).read_text())
        if (root / DOWNLOADS_FILE).exists()
        else {}
    )
    pins = read_pins(root)
    lines = [
        "# Data sources",
        "",
        "_Generated by `deltaaudit download` from `configs/datasets/*.yaml` and "
        "`data/downloads.json`. Do not edit by hand._",
        "",
    ]
    for cfg in configs:
        lines += [f"## {cfg['name']}", "", cfg.get("description", ""), ""]
        for a in cfg["assets"]:
            rec = records.get(cfg["name"], {}).get(a["id"])
            lines += [
                f"### `{a['id']}`",
                "",
                f"- URL: <{a['url']}>",
                *(
                    [
                        f"- Dataverse file id: {a['dataverse_file_id']} ({a['dataverse_doi']})"
                    ]
                    if "dataverse_file_id" in a
                    else []
                ),
                f"- Licence: {a['licence']}",
                f"- Citation: {a['citation']}",
            ]
            if rec is None:
                lines += ["- Not downloaded yet.", ""]
                continue
            lines += [
                f"- Downloaded (UTC): {rec['downloaded_utc']}",
                f"- Size: {rec['bytes']:,} bytes",
                f"- SHA-256: `{rec['sha256']}`",
                f"- MD5: `{rec['md5']}`"
                + (" (matches Dataverse)" if a.get("md5") == rec["md5"] else ""),
            ]
            for rel in rec.get("extracted", []):
                lines.append(f"  - extracted `{rel}` sha256 `{pins.get(rel, '?')}`")
            lines.append("")
    out = root / SOURCES_FILE
    out.write_text("\n".join(lines))
    return out
